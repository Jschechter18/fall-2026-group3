"""Write AUDIT.md: how each final label was decided and every reconciliation, with question IDs. Read-only on inputs."""
import argparse
import json
from collections import Counter
from pathlib import Path

from mas_sae.experiments.records import read_jsonl

import final_labels as fl

STEPS = {"proposal": "Earlier proposal rules (`proposal_snapshot.py`)",
         "guard": "Out: letter-only reply, citation mark, or not in the frozen partitions",
         "addition": "Last rules for episodes the proposal left out",
         "moved_out": "Out: the Critic's reply contains A1's short answer (previous label kept)",
         "v020_usable": "Usable under v0.2.0 and partitioned: keeps its adoption/retention label"}


def short(text, limit=90):
    text = " ".join((text or "").split())
    return text if len(text) <= limit else text[:limit - 1] + "…"


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c).replace("|", "\\|") for c in row) + " |" for row in rows]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--run", required=True, type=Path)
    parser.add_argument("--earlier-run", type=Path, help="natural_4b_full9 run, to look up unpartitioned IDs")
    args = parser.parse_args()
    here = Path(__file__).resolve().parent
    manifest = json.loads((here / "counts.json").read_text())
    records = fl.build(args.run, here.parents[2] / "results/behavior/behavior_v012_official_20261011/partitions.csv")
    if fl.labels_sha256(records) != manifest["labels_sha256"]:
        raise ValueError("the labels built from this run differ from the approved labels in counts.json")
    text = {r["question_id"]: r for s in fl.SPLITS for r in read_jsonl(args.run / s / "interactions.jsonl")}
    by_id = {r["question_id"]: r for r in records}
    total = len(records)
    has = lambda r, f: f in r["flags"]
    qa = lambda q: [q, short(text[q]["solver_attempt_1"]), short(text[q]["critic_advocated_answer"]), short(text[q]["solver_attempt_2"])]
    out = [f"# Audit: final candidate behavior labels\n",
           f"Policy `{manifest['policy_version']}`, {total:,} sampled questions. Generated by `audit.py` from a fresh build "
           f"(sha256 `{manifest['labels_sha256'][:16]}…`, matching `counts.json`); every number below is counted from it.\n"]

    labels = Counter(r["label"] for r in records)
    out += ["## Final counts\n", table(["Label", "Episodes", "Share"],
                                       [[k, f"{labels[k]:,}", f"{labels[k] / total:.1%}"] for k in fl.LABELS]), ""]
    ar, usable = labels["adoption"] + labels["retention"], sum(r["v020_eligible_strict"] for r in records)
    out += [f"Adoption + retention: {ar:,} ({ar / total:.1%}), against {usable:,} ({usable / total:.1%}) usable under v0.2.0. "
            f"Three-class coverage: {ar + labels['agreement']:,} ({(ar + labels['agreement']) / total:.1%}).\n"]
    parts = ["train", "validation", "test", "intervention", None]
    out += [table(["Partition", *fl.LABELS], [[p or "not in frozen file", *(f"{sum(r['label'] == k and r['partition'] == p for r in records):,}"
                                                                         for k in fl.LABELS)] for p in parts]), ""]

    steps = Counter((r["step"], r["label"]) for r in records)
    out += ["## How each label was decided\n", "Steps run in this order; each row counts the episodes whose final label it set.\n",
            table(["Step", *fl.LABELS, "total"], [[STEPS[s], *(f"{steps[(s, k)]:,}" for k in fl.LABELS),
                                                   f"{sum(steps[(s, k)] for k in fl.LABELS):,}"] for s in STEPS]), ""]

    flagged_br = [r for r in records if has(r, "both_refused")]
    not_agree = [r for r in flagged_br if r["label"] != "agreement"]
    out += ["## Both refused\n",
            f"{len(flagged_br):,} episodes have both A1 and the Critic refusing. {len(flagged_br) - len(not_agree):,} are Agreement "
            f"because A2 kept refusing. The other {len(not_agree)} are Out because A2 did not keep refusing:\n",
            table(["question_id", "A1", "C1", "A2", "label", "reason"], [qa(r["question_id"]) + [r["label"], r["reason"]] for r in not_agree]), ""]

    shape = [r for r in records if r["collected"] and r["proposal_label"] in ("adoption", "retention")
             and fl.critic_mentions_a1(text[r["question_id"]])]
    moved = [r for r in shape if r["step"] == "moved_out"]
    other = [r for r in shape if r["step"] != "moved_out"]
    out += ["## Critic's reply contains A1's answer\n",
            f"{len(shape):,} episodes had this shape and an adoption/retention proposal label. {len(moved):,} were moved Out "
            f"({sum(r['previous_label'] == 'adoption' for r in moved)} adoption, {sum(r['previous_label'] == 'retention' for r in moved)} retention; "
            f"`previous_label` keeps it). The other {len(other)} were already Out through an earlier guard:\n",
            table(["question_id", "A1", "C1", "A2", "reason"], [qa(r["question_id"]) + [r["reason"]] for r in other]), "",
            f"Two team reference cases (Bordeaux, Marvin Gaye) are among the moved episodes.\n"]

    kept = [r for r in records if r["step"] == "v020_usable"]
    for flag, title in (("letter_reply", "Letter-only replies kept because v0.2.0 already used them"),
                        ("citation_only", "Citation-mark replies kept because v0.2.0 already used them")):
        rows = [r for r in kept if has(r, flag)]
        out += [f"## {title}\n", f"{len(rows)} episodes. v0.2.0 labeled each as a flip or stay; that label is kept and the flag "
                f"stays for sensitivity runs. All other {flag} episodes are Out.\n",
                table(["question_id", "partition", "A2", "letter side", "label"],
                      [[r["question_id"], r["partition"], short(text[r["question_id"]]["solver_attempt_2"], 40), r["letter_side"] or "", r["label"]]
                       for r in rows]), ""]

    hyphen = [r for r in records if r["v020_eligible_strict"] and r["label"] == "agreement"]
    out += ["## Usable under v0.2.0, now Agreement\n",
            f"{len(hyphen)} episodes. A1 and C1 are the same text apart from hyphen spacing, so they agree, like team reference case 3.\n",
            table(["question_id", "A1", "C1", "A2"], [qa(r["question_id"]) for r in hyphen]), ""]

    unmapped = [r for r in records if r["partition"] is None and r["collected"]]
    earlier = {}
    if args.earlier_run:
        earlier = {e["question_id"]: e for s in fl.SPLITS for e in read_jsonl(args.earlier_run / s / "exclusions.jsonl")}
    out += ["## Not in the frozen partitions\n",
            f"{sum(r['partition'] is None for r in records)} sampled questions have no frozen partition: "
            f"{sum(r['partition'] is None and not r['collected'] for r in records)} collection failures and {len(unmapped)} collected episodes. "
            "The frozen partitions cover only the episodes collected in the earlier natural run. All are Out (quarantined).\n",
            table(["question_id", "label", "v0.2.0 usable", "earlier run"],
                  [[r["question_id"], r["label"], r["v020_eligible_strict"],
                    f"failed at {earlier[r['question_id']]['stage']}" if r["question_id"] in earlier else "not checked"] for r in unmapped]), ""]

    reviewed = [by_id[q] for q in fl.TEAM_REVIEWED]
    differ = [r for r in reviewed if r["label"] != r["team_label"]]
    out += ["## Team-reviewed reference cases\n",
            f"{len(reviewed)} episodes (the eight reference cases and the second-review examples) have a team label. It is recorded "
            f"in `team_label` and never applied. The rules agree on {len(reviewed) - len(differ)}. On the other {len(differ)}, the rules "
            "leave the episode Out; they never give a different class:\n",
            table(["question_id", "team label", "final label", "reason"],
                  [[r["question_id"], r["team_label"], r["label"], r["reason"]] for r in differ]), ""]

    hybrids = [r for r in records if has(r, "potential_hybrid")]
    out += ["## Hybrid candidates\n", f"{len(hybrids)} Out episodes matched the hybrid search (A2 keeps words found only in A1 and "
            "words found only in C1). This is one search, not an exhaustive count.\n",
            table(["question_id", "A1", "C1", "A2"], [qa(r["question_id"]) for r in hybrids]), ""]

    out += ["## Sources\n", table(["file", "sha256"], [[k, v[:16] + "…"] for k, v in manifest["sources"].items()]), "",
            "Tests: `PYTHONPATH=src:results/experiments/candidate_final_labels_20261027 python -m pytest -p no:cacheprovider "
            "results/experiments/candidate_final_labels_20261027/test_final_labels.py`\n"]
    (here / "AUDIT.md").write_text("\n".join(out))
    print("wrote", here / "AUDIT.md")


if __name__ == "__main__":
    main()
