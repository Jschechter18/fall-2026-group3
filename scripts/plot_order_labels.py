"""Paper figure and tables for the candidate-order breakdown of the PR #153 labels (issue #166).

Reads the ``summary.json`` written by ``summarize_order_labels.py`` and writes:

* ``<figures>/candidate_order_adoption.{svg,pdf}``: (a) Adoption share of Adoption + Retention by
  the candidate order the Solver saw; (b) the same for useful corrections (A1 wrong, Critic right)
  and harmful ones (A1 right, Critic wrong). Dots are shares, bars 95% Wilson intervals.
* ``<tables>/candidate_order_labels.csv``: four-class counts and the Adoption share per partition
  and order; ``candidate_order_correctness.csv``: the same per correctness case;
  ``candidate_order_labels.tex``: a booktabs table for the paper.

Usage:
    python scripts/plot_order_labels.py \\
        --summary results/claude_validation/candidates_order_breakdown/summary.json \\
        --figures reports/figures/candidate_order_balance \\
        --tables reports/tables/candidate_order_balance
"""

import argparse
import csv
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ORDERS = ("a1_first", "critic_first", "both")
ORDER_NAMES = {"a1_first": "A1 first", "critic_first": "Critic first", "both": "Both orders"}
SCOPES = ("train", "validation", "test", "intervention", "all")
CASES = {"useful_correction": "Useful correction\n(A1 wrong, Critic right)",
         "harmful_correction": "Harmful correction\n(A1 right, Critic wrong)"}
# Categorical slots 1-2 of the reference palette (validated: CVD dE 24.7); "both" is the aggregate, in ink.
COLORS = {"a1_first": "#2a78d6", "critic_first": "#eb6834", "both": "#52514e"}
MARKERS = {"a1_first": "o", "critic_first": "s", "both": "D"}
INK, MUTED, GRID = "#1f1f1e", "#6b6a66", "#e4e3df"


def adoption(d: dict) -> dict:
    """Adoption share of Adoption + Retention with its 95% interval, from a label_distribution."""
    b = d["retention_share_of_binary"]
    lo, hi = b["ci95"]
    return {"adoption": d["adoption"]["count"], "retention": d["retention"]["count"],
            "agreement": d["agreement"]["count"], "out": d["out"]["count"], "binary": b["binary"],
            "adoption_share": 1 - b["share"], "ci_low": 1 - hi, "ci_high": 1 - lo}


def table_rows(summary: dict) -> tuple[list[dict], list[dict]]:
    by_order = [{"partition": s, "order": o, **adoption(summary["by_order"][s][o])} for s in SCOPES for o in ORDERS]
    by_case = [{"partition": s, "case": c, "order": o, **adoption(summary["by_correctness"][s][c][o])}
               for s in SCOPES for c in CASES for o in ORDERS]
    return by_order, by_case


def write_csv(path: Path, rows: list[dict]) -> None:
    with path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def latex_table(rows: list[dict], labels_sha256: str) -> str:
    """Booktabs table over all frozen partitions, one row per order."""
    body = []
    for r in (r for r in rows if r["partition"] == "all"):
        body.append(f"        {ORDER_NAMES[r['order']]} & {r['adoption']:,} & {r['retention']:,} & {r['agreement']:,} & "
                    f"{r['out']:,} & {r['adoption_share']:.1%} [{r['ci_low']:.1%}, {r['ci_high']:.1%}] \\\\"
                    .replace("%", "\\%"))
    body.insert(2, "        \\midrule")
    return "\n".join([
        f"% Generated by scripts/plot_order_labels.py from PR #153 labels (sha256 {labels_sha256[:12]}...).",
        "\\begin{table}[htbp]",
        "    \\centering",
        "    \\caption{PR \\#153 behavior labels by the candidate order the Solver saw (assigned before A2), "
        "collected episodes in all frozen partitions; Out therefore excludes collection failures. "
        "Adoption share is Adoption / (Adoption + Retention), with a 95\\% Wilson interval.}",
        "    \\label{tab:candidate-order-labels}",
        "    \\begin{tabular}{lrrrrc}",
        "        \\toprule",
        "        Candidate order & Adoption & Retention & Agreement & Out & Adoption share \\\\",
        "        \\midrule", *body, "        \\bottomrule", "    \\end{tabular}", "\\end{table}", ""])


def style(ax, title: str) -> None:
    ax.set_title(title, loc="left", fontsize=10, color=INK, pad=8)
    ax.axhline(0.5, color=MUTED, linewidth=1, linestyle=(0, (4, 3)), zorder=1)
    ax.yaxis.grid(True, color=GRID, linewidth=0.8, zorder=0)
    ax.set_axisbelow(True)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color(MUTED)
    ax.tick_params(colors=MUTED, labelcolor=INK, labelsize=9, length=0)
    ax.yaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(1.0, decimals=0))


def point(ax, x: float, r: dict, order: str) -> None:
    ax.errorbar(x, r["adoption_share"], yerr=[[r["adoption_share"] - r["ci_low"]], [r["ci_high"] - r["adoption_share"]]],
                fmt=MARKERS[order], markersize=8, color=COLORS[order], ecolor=COLORS[order], elinewidth=2,
                capsize=4, capthick=2, markeredgecolor="white", markeredgewidth=1.5, zorder=3)
    ax.annotate(f"{r['adoption_share']:.1%}", (x, r["adoption_share"]), xytext=(9, 0), textcoords="offset points",
                va="center", fontsize=8.5, color=INK)


def plot(by_order: list[dict], by_case: list[dict], outputs: list[Path]) -> None:
    fig, (left, right) = plt.subplots(1, 2, figsize=(7.2, 3.4), sharey=True, gridspec_kw={"width_ratios": [1, 1.15]})
    scoped = {r["order"]: r for r in by_order if r["partition"] == "all"}
    for x, order in enumerate(ORDERS):
        point(left, x, scoped[order], order)
    left.set_xticks(range(len(ORDERS)), [f"{ORDER_NAMES[o]}\n(n = {scoped[o]['binary']:,})" for o in ORDERS])
    left.set_xlim(-0.5, len(ORDERS) - 0.3)
    left.set_ylabel("Adoption share of Adoption + Retention", fontsize=9, color=INK)
    style(left, "(a) By candidate order")
    left.text(len(ORDERS) - 0.35, 0.5, "parity", fontsize=8, color=MUTED, ha="right", va="bottom")

    for x, case in enumerate(CASES):
        for offset, order in ((-0.17, "a1_first"), (0.17, "critic_first")):
            r = next(r for r in by_case if r["partition"] == "all" and r["case"] == case and r["order"] == order)
            point(right, x + offset, r, order)
    right.set_xticks(range(len(CASES)), list(CASES.values()))
    right.set_xlim(-0.55, len(CASES) - 0.35)
    style(right, "(b) By whether the Critic's correction was right")
    handles = [plt.Line2D([], [], marker=MARKERS[o], color=COLORS[o], linestyle="", markersize=7, label=ORDER_NAMES[o])
               for o in ("a1_first", "critic_first")]
    right.legend(handles=handles, frameon=False, fontsize=8.5, loc="lower left", handletextpad=0.3)

    lows = [r["ci_low"] for r in (*scoped.values(), *(r for r in by_case if r["partition"] == "all"))]
    highs = [r["ci_high"] for r in (*scoped.values(), *(r for r in by_case if r["partition"] == "all"))]
    left.set_ylim(min(0.3, min(lows) - 0.03), max(0.7, max(highs) + 0.03))
    fig.tight_layout()
    for path in outputs:
        fig.savefig(path, bbox_inches="tight", facecolor="white")
    plt.close(fig)


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--summary", type=Path, required=True)
    parser.add_argument("--figures", type=Path, required=True)
    parser.add_argument("--tables", type=Path, required=True)
    args = parser.parse_args(argv)

    summary = json.loads(args.summary.read_text())
    by_order, by_case = table_rows(summary)
    args.figures.mkdir(parents=True, exist_ok=True)
    args.tables.mkdir(parents=True, exist_ok=True)
    write_csv(args.tables / "candidate_order_labels.csv", by_order)
    write_csv(args.tables / "candidate_order_correctness.csv", by_case)
    (args.tables / "candidate_order_labels.tex").write_text(latex_table(by_order, summary["labels_sha256"]), encoding="utf-8")
    plot(by_order, by_case, [args.figures / "candidate_order_adoption.svg", args.figures / "candidate_order_adoption.pdf"])
    for r in by_order:
        if r["partition"] == "all":
            print(f"{ORDER_NAMES[r['order']]:12s} {r['adoption_share']:.1%} [{r['ci_low']:.1%}, {r['ci_high']:.1%}]")


if __name__ == "__main__":
    main()
